struct Row {
  std::string text,
      speaker; // UTF-8 retaining the effective game's glyph codepoints.
  int32_t voice{-1};
  uint32_t physical_slot{};
  bool operator==(const Row &) const = default;
};
struct Snapshot {
  bool compatible{}, ready{}, cg_ready{};
  uint64_t story{}, epoch{};
  int32_t head{}, selected{-1}, native_mode{-1};
  // False while the main-screen text window is empty: the newest ring row is then past dialogue
  // too. True (the conservative default) when it shows a line or the field cannot be read.
  bool text_visible{true};
  std::vector<Row> rows; // Oldest to newest, never more than63.
  std::array<uint8_t, 53> cg_flags{};
};
using ReadFn = std::function<bool(uint64_t, void *, size_t)>;
bool SupportsBuild(std::string_view build);
// Bounded, build-specific snapshot. Caller's reader must reject unmapped
// ranges. Incomplete/torn state returns readiness=false with no stale rows or
// flags.
Snapshot ReadSnapshot(const ReadFn &, uint64_t main_base, bool build_matches);
bool IsContinuation(const Snapshot &previous, const Snapshot &next);
class Reader {
public:
  explicit Reader(const EdenDsmodHostApi &) {}
  void Sample(const EdenDsmodHostApi &);
  const Snapshot &GetSnapshot() const { return snapshot_; }
  // Hardening (2026-10-17): moves snapshot_ out instead of copying it. The one caller
  // (yoru_module.cpp's Module::Sample) always calls this right after Sample() and always ends up
  // handing the result to its own state.snapshot anyway, so there is no reason to deep-copy the
  // (up to 63-row, string-holding) Snapshot first via GetSnapshot() -- that copy ran unconditionally
  // every tick regardless of whether anything had changed. Leaving snapshot_ moved-from here is
  // safe: the only thing that ever reads it again is the next Sample() call, which unconditionally
  // overwrites it (snapshot_ = std::move(next);) before anyone could observe the gap.
  Snapshot TakeSnapshot() { return std::move(snapshot_); }

private:
  Snapshot snapshot_;
  uint64_t epoch_{};
  bool last_raw_text_visible_{true};
};
