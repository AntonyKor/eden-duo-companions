#!/usr/bin/env python3
"""Generate native/modules/va11_jill_faces.h from native/modules/va11_jill_faces/<file>.tsv.

The tables are our own reading of each day: at which script line Jill's face on the stand-by
screen changes (it holds until the next entry; every day starts neutral). They hold line numbers
and face names only, never game text. The module reads the player's own script files at runtime
and finds the line on screen (see JillTick in 010086500D3C8000.cpp).

usage: tools/va11-hall-a/gen_jill_faces.py                          writes the header
       tools/va11-hall-a/gen_jill_faces.py --check <scripts/eng>    also prints each entry beside its line
                                                        (for review on the PC; prints game text)
"""
import argparse
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
SRC = ROOT / "native/modules/va11_jill_faces"
OUT = ROOT / "native/modules/va11_jill_faces.h"
FACES = ["neutral", "smile", "surprise", "uh", "sad", "think", "baka"]
# The dialogue files in the module's order (kFiles in 010086500D3C8000.cpp): a table's file number is its
# place here, counted from 1. A table is named after its file, "/" as "_" (1.2_anna.tsv).
FILES = [f"script{i}" for i in range(1, 20)] + [
    "tutorial_switch", "tutorial", "epilogues", "gameover", "1.2/anna", "1.2/pro1", "1.2/pro2", "1.2/pro3",
    "anna_script.ini"]


def read_tables():
    entries = []
    names = [n.replace("/", "_") for n in FILES]
    for f in sorted(SRC.glob("*.tsv"), key=lambda p: names.index(p.stem) if p.stem in names else -1):
        if f.stem not in names:
            raise SystemExit(f"{f.name}: no dialogue file of that name")
        script = names.index(f.stem) + 1
        last = 0
        for n, row in enumerate(f.read_text(encoding="utf-8").splitlines(), 1):
            if not row.strip() or row.startswith("#"):
                continue
            cols = row.split("\t")
            line, face = int(cols[0]), cols[1].strip()
            if face not in FACES:
                raise SystemExit(f"{f.name}:{n}: unknown face {face!r}")
            if line <= last:
                raise SystemExit(f"{f.name}:{n}: line {line} is not after {last}")
            last = line
            entries.append((script, line, face, cols[2].strip() if len(cols) > 2 else ""))
    return entries


def write_header(entries):
    rows = "\n".join(f"    {{{s}, {l}, {FACES.index(f)}}}, // {f}" for s, l, f, _ in entries)
    OUT.write_text(f"""// Generated by tools/va11-hall-a/gen_jill_faces.py from native/modules/va11_jill_faces/*.tsv -- do not edit.
// Jill's face from file <script> (kFiles[script - 1]) line <line> on (0 neutral, 1 smile, 2 surprise, 3 uh, 4 sad,
// 5 think, 6 baka), sorted; the last entry is an end marker.
#pragma once

struct JillFaceEntry {{
    unsigned char script;
    unsigned short line;
    unsigned char face;
}};

constexpr JillFaceEntry kJillFaces[] = {{
{rows}
    {{255, 0, 0}},
}};
""", encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(ROOT)}: {len(entries)} entries")


def check(entries, scripts):
    for s, l, f, note in entries:
        text = (pathlib.Path(scripts) / f"{FILES[s - 1]}.txt").read_text(encoding="utf-8-sig").splitlines()
        raw = text[l - 1] if l <= len(text) else "<past the end>"
        shown = re.sub(r"\[[^\]]*\]", "", raw).strip()
        print(f"{FILES[s - 1]:15} {l:5} {f:9} {'' if shown else '<EMPTY LINE> '}{shown[:90]}  [{note}]")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", metavar="SCRIPTS_DIR")
    a = ap.parse_args()
    e = read_tables()
    write_header(e)
    if a.check:
        check(e, a.check)
